/**
 * @module Infrastructure/RenderLib/Aggregator/ReaderGuideDescriptionsI18n
 * @category Intelligence Operations / Supporting Infrastructure
 * @name Centralised reader-value (description) translations for every analysis artifact
 *
 * @description
 * Single source of truth for the per-artifact "reader value" sentences
 * shown in the Reader Intelligence Guide table and the Analysis Sources
 * card grid. Structured exactly like
 * {@link ../../political-intelligence/i18n/artifact-i18n.js#ARTIFACT_TITLE_I18N}
 * — `Record<filename, LangMap>` — so adding a new artifact requires
 * exactly one entry covering all 14 languages.
 *
 * Why a separate map (rather than 14 per-language ENTRIES blocks)?
 *
 * - Eliminates the silent fallback to the generic
 *   "supporting analytical lens with primary-source evidence and
 *   audit-traceable citations" sentence that previously repeated
 *   itself across 15+ rows in every rendered article.
 * - One source of truth means new artifacts get translated in all 14
 *   languages in a single, reviewable diff — no risk of one language
 *   silently lagging the other 13.
 * - Reused by both the markdown table builder
 *   ({@link ./reader-guide.js#buildReaderGuide}) and the HTML
 *   navigation table + sources cards ({@link ../article-aside.js}).
 *
 * Lookup precedence used by callers:
 *
 *   1. Per-language curated entry in {@link ./reader-guide-i18n.js}
 *      (existing 7 lenses; localised label + readerValue tuned per
 *      language).
 *   2. Centralised entry in this file (covers everything else).
 *   3. Generic English {@link ./reader-guide.js#READER_GUIDE_ENTRIES}
 *      curated default.
 *   4. Localised `defaultReaderValue` from
 *      {@link ./reader-guide-i18n.js} chrome.
 *
 * @author Hack23 AB (Infrastructure Team)
 * @license Apache-2.0
 */

