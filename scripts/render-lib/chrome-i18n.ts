/**
 * @module Infrastructure/RenderLib/Chrome/I18n
 * @category Intelligence Operations / Supporting Infrastructure
 * @name CHROME_I18N — Per-language footer & header chrome strings (14 languages)
 *
 * @description
 * Pure data module — `ChromeStrings` shape + `CHROME_I18N` map (one entry
 * per supported `Language`). Every user-visible string in the site
 * header (CTAs, theme toggle, skip-link) and the site footer (column
 * headings, link labels, ISMS column, Transparency & compliance column,
 * trust-badges aria-labels, language-switcher row, copyright legal line)
 * is sourced from this table so that all 14 supported languages render
 * the same chrome in their own language rather than English fallback.
 *
 * Proper-noun standards names that are themselves part of the ISMS
 * vocabulary (ISO 27001:2022, NIST CSF 2.0, CIS Controls v8.1, EU CRA,
 * NIS2, GDPR, CodeQL, OpenSSF, Apache-2.0, Hack23, Riksdagsmonitor) are
 * intentionally kept identical across languages — they are brand /
 * specification names, not translatable text.
 *
 * Used by:
 *   - `scripts/render-lib/chrome.ts` (modern site chrome — all generated
 *     pages: home, dashboard, sitemap, political-intelligence, news
 *     index, generated articles)
 *   - `scripts/normalize-static-html-chrome.ts` (legacy news article
 *     header + footer)
 *   - `scripts/backfill-translated-chrome.ts` (post-processor that
 *     surgically injects the new chrome blocks into already-translated
 *     historical articles without retranslating the body)
 *
 * @author Hack23 AB (Infrastructure Team)
 * @license Apache-2.0
 */

